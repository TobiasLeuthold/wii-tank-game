// Guard against typos: force exactly ROWS x COLS.
function toLevel(rows, label) {
  const fixed = [];
  for (let r = 0; r < ROWS; r++) {
    const row = rows[r] || '';
    if (row.length !== COLS) console.warn(`${label} row ${r} has ${row.length} columns`);
    fixed.push(row.padEnd(COLS, '.').slice(0, COLS));
  }
  return { map: fixed };
}

// Enemy type letters in a mission, in map order.
function levelEnemies(level) {
  const out = [];
  for (const row of level.map) for (const ch of row) if (ENEMY_TYPES[ch]) out.push(ch);
  return out;
}
